export type Strings = typeof EN;

export function strings(language: string | undefined): Strings {
  const lang = (language || "en").split("-")[0];
  return lang === "de" ? DE : EN;
}

export function fill(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ""));
}

export interface Alert {
  severity: string;
  message: string;
  key?: string;
  params?: Record<string, any>;
}

/** Translated alert text; falls back to the English message from the integration. */
export function alertText(t: Strings, a: Alert): string {
  const tpl = a.key ? t.alert_text[a.key] : undefined;
  if (!tpl) return a.message;
  const p = a.params ?? {};
  return fill(tpl, {
    reasons: (p.reasons ?? []).map((r: string) => t.lock_reasons[r] ?? r).join(", "),
    phase: t.phases[p.phase] ?? p.phase ?? "",
    to: p.to ? t.phases[p.to] ?? p.to : "–",
  });
}
